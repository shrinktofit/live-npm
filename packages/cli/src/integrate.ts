import { access, mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import {
  createPnpmHooksCjs,
  createPnpmfileMergeSnippet,
  createPnpmfileCjs,
  createRootPnpmfileShim,
} from './pnpm-hook-template.js';

export interface IntegrateOptions {
  host: string;
  port: number;
  projectDir: string;
}

export interface IntegrateResult {
  createdRootPnpmfile: boolean;
  liveDir: string;
  rootPnpmfilePath?: string;
  snippetPath?: string;
}

const liveDirName = '.live-npm';

export async function integrateProject(options: IntegrateOptions): Promise<IntegrateResult> {
  const projectDir = path.resolve(options.projectDir);
  await assertPnpm11Project(projectDir);

  const liveDir = path.join(projectDir, liveDirName);
  await mkdir(liveDir, { recursive: true });
  await writeFile(path.join(liveDir, 'pnpm-hooks.cjs'), createPnpmHooksCjs({
    defaultHost: options.host,
    defaultPort: options.port,
  }));
  await writeFile(path.join(liveDir, 'pnpmfile.cjs'), createPnpmfileCjs());
  await writeFile(path.join(liveDir, '.gitignore'), liveGitignore());
  await writeFile(path.join(liveDir, 'README.md'), liveReadme());
  await writeFileIfMissing(path.join(liveDir, 'config.yaml'), defaultConfigYaml());

  const rootPnpmfilePath = await findRootPnpmfile(projectDir);
  if (!rootPnpmfilePath) {
    const generatedRootPnpmfile = path.join(projectDir, '.pnpmfile.cjs');
    await writeFile(generatedRootPnpmfile, createRootPnpmfileShim());
    return {
      createdRootPnpmfile: true,
      liveDir,
      rootPnpmfilePath: generatedRootPnpmfile,
    };
  }

  const snippetPath = path.join(liveDir, 'pnpmfile-snippet.cjs');
  await writeFile(snippetPath, createPnpmfileMergeSnippet());
  return {
    createdRootPnpmfile: false,
    liveDir,
    rootPnpmfilePath,
    snippetPath,
  };
}

async function assertPnpm11Project(projectDir: string): Promise<void> {
  const packageJsonPath = path.join(projectDir, 'package.json');
  const manifest = JSON.parse(await readFile(packageJsonPath, 'utf8')) as { packageManager?: unknown };
  if (typeof manifest.packageManager !== 'string') {
    throw new Error(`${packageJsonPath} must declare packageManager: pnpm@11 or newer.`);
  }
  const match = /^pnpm@(\d+)\./.exec(manifest.packageManager);
  if (!match) {
    throw new Error(`${packageJsonPath} packageManager must use pnpm@11 or newer.`);
  }
  const major = Number(match[1]);
  if (!Number.isInteger(major) || major < 11) {
    throw new Error(`${packageJsonPath} packageManager must use pnpm@11 or newer.`);
  }
}

async function findRootPnpmfile(projectDir: string): Promise<string | undefined> {
  for (const fileName of ['.pnpmfile.mjs', '.pnpmfile.cjs']) {
    const file = path.join(projectDir, fileName);
    if (await exists(file)) {
      return file;
    }
  }
  return undefined;
}

async function writeFileIfMissing(file: string, contents: string): Promise<void> {
  if (await exists(file)) {
    return;
  }
  await writeFile(file, contents);
}

async function exists(file: string): Promise<boolean> {
  try {
    await access(file);
    return true;
  } catch {
    return false;
  }
}

function defaultConfigYaml(): string {
  return `# live-npm project config.
# Add source packages or workspaces here. Generated runtime files stay under .live-npm.
debounceMs: 200
packages: []
workspaces: []
`;
}

function liveGitignore(): string {
  return `store/
*.log
`;
}

function liveReadme(): string {
  return `# live-npm local files

This directory is generated by live-npm. Add \`.live-npm/\` to your project \`.gitignore\` unless you explicitly want to share this local integration.

Edit \`config.yaml\` to declare the source packages or pnpm workspaces that may be resolved through \`live:\` dependency specs.
`;
}
